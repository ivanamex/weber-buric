-- The sign-in screen leads with the demo while the club presents the app; management turns it off in Ajustes once
-- real families sign in. Safe to run twice.

alter table club_settings add column if not exists promote_demo boolean not null default true;

-- Read before signing in (nothing personal: one yes/no).
create or replace function promote_demo() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select promote_demo from club_settings where id = 1), true)
$$;

